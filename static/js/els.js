// 启动时校验关键 DOM 元素，缺 id 时立即报错，避免运行到一半才崩溃
export function assertElements() {
  const missing = Object.entries(els)
    .filter(([, el]) => !el)
    .map(([k]) => k);
  if (missing.length) throw new Error('缺少页面元素：' + missing.join(', '));
}
